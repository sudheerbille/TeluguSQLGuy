-- LAG SCENARIO 1 - DAY-OVER-DAY GROWTH

CREATE OR REPLACE TABLE SALES_REVENUE (
    SALE_DATE DATE,
    REVENUE NUMBER(10,2)
);

INSERT INTO SALES_REVENUE (SALE_DATE, REVENUE)
VALUES
    ('2026-09-01', 100),
    ('2026-09-04', 349),
    ('2026-09-03', 75),
    ('2026-09-02', 200),
    ('2026-09-05', 250),
    ('2026-09-06', 148),
    ('2026-09-07', 125);


-- EXPECTED OUTPUT

-- SALE_DATE TODAYS_REVENUE	YESTERDAYS_REVENUE	DAILY_GROWTH

SELECT SALE_DATE,
       REVENUE AS TODAYS_REVENUE,
       LAG(REVENUE,1,0) OVER (ORDER BY SALE_DATE ASC) AS YESTERDAYS_REVENUE,
       (TODAYS_REVENUE - YESTERDAYS_REVENUE) AS DAILY_GROWTH
       
       
FROM DAILY_SALES;

-- LAG - SCENARIO 2 - DAY-OVER-DAY GROWTH - REGION WISE
CREATE OR REPLACE TABLE SALES_REVENUE_REGION (
    SALE_DATE DATE,
    REVENUE NUMBER(10,2),
    REGION VARCHAR(20)
);

INSERT INTO SALES_REVENUE_REGION (SALE_DATE, REVENUE, REGION)
VALUES
    ('2026-09-05', 100, 'NORTH'),
    ('2026-09-02', 200, 'SOUTH'),
    ('2026-09-06', 75,  'NORTH'),
    ('2026-09-03', 349, 'SOUTH'),
    ('2026-09-07', 250, 'NORTH'),
    ('2026-09-01', 148, 'SOUTH'),
    ('2026-09-08', 125, 'NORTH'),
    ('2026-09-04', 265, 'SOUTH');


-- EXPECTED OUTPUT - CALCULATED SEPERATELY FOR EACH REGION

-- REGION	SALE_DATE	TODAYS_REVENUE	YESTERDAYS_REVENUE	DAILY_GROWTH

SELECT REGION,
       SALE_DATE,
       REVENUE AS TODAYS_REVENUE,
       LAG(REVENUE,1,0)OVER(PARTITION BY REGION ORDER BY SALE_DATE ASC) AS YESTERDAYS_REVENUE,
       (TODAYS_REVENUE - YESTERDAYS_REVENUE) AS DAILY_GROWTH
       
FROM REGIONAL_SALES;

-- LEAD - SCENARIO - USER CLICK STREAM DATA

CREATE OR REPLACE TABLE USER_PAGE_CLICKS (
    USER_ID NUMBER,
    PAGE_NAME VARCHAR(50),
    CLICK_TIME TIMESTAMP_NTZ
);

INSERT INTO USER_PAGE_CLICKS (USER_ID, PAGE_NAME, CLICK_TIME)
VALUES
    (101, 'Home Page',    '2026-09-07 10:00:00'),
    (101, 'Product Page', '2026-09-07 10:02:30'),
    (101, 'Cart Page',    '2026-09-07 10:05:00'),
    (101, 'Checkout',     '2026-09-07 10:08:15'),
    (102, 'Home Page',    '2026-09-07 10:10:00'),
    (102, 'Search',       '2026-09-07 10:11:15'),
    (102, 'Product Page', '2026-09-07 10:14:00'),
    (103, 'Landing Page', '2026-09-07 10:20:00'),
    (103, 'Pricing Page', '2026-09-07 10:21:45');

-- EXPECTED OUTPUT
-- USER_ID PAGE_NAME CLICK_TIME NEXT_CLICK_TIME DURATION

SELECT USER_ID,
       PAGE_NAME,
       CLICK_TIME,
       LEAD(CLICK_TIME)OVER(PARTITION BY USER_ID ORDER BY USER_ID ASC, CLICK_TIME ASC) AS NEXT_CLICK_TIME,
       ROUND(DATEDIFF('SECOND',CLICK_TIME,NEXT_CLICK_TIME)/60,2) ||' '|| 'MINUTES' AS DURATION
       
FROM USER_CLICKS
ORDER BY USER_ID;
